#!/usr/bin/env python3
"""glm-rollouts-sftv3 (2026-11-07; kimi-rollouts-v4's make_baihe_secrets.py, unchanged code; this directory's own file, never a copy of v4's secrets): write secrets/baihe-opensandbox.env (dir 700, file 600) for the campaigns of Baihe's tasks (user, 2026-10-26 ~01:10: "For baihe's sandbox tasks, use another sandbox API Key BAIHE_SANDBOX_API_KEY in .env").

Same contents and format as S/secrets/opensandbox.env (S/tools/make_secrets.py, whose parser / renderer / atomic writer are
reused unchanged by loading that module from its path), except that OPENSANDBOX_API_KEY is the value of
BAIHE_SANDBOX_API_KEY in /lustre/fsw/portfolios/nemotron/users/hengyuf/.env (read by NAME, literally, never printed):
    OPENSANDBOX_DOMAIN (make_secrets.DOMAIN, the same OpenSandbox server), OPENSANDBOX_API_KEY,
    OPENSANDBOX_TLS_VERIFY=false, OPENSANDBOX_USE_SERVER_PROXY=true
Refuses when the value equals CELL3_SANDBOX_API_KEY (the credential S/atp/.env gives every other campaign). Read by
probe_worker.py (KR3_SANDBOX=baihe) and by baihe_snapshot_check.py. Prints names only.

    /usr/bin/python3 -I -B make_baihe_secrets.py [--check]
"""
import sys

sys.dont_write_bytecode = True

import argparse  # noqa: E402
import importlib.util  # noqa: E402
import os  # noqa: E402
from pathlib import Path  # noqa: E402
import stat  # noqa: E402

HERE = Path(__file__).resolve().parent
SECRETS = HERE / "secrets"
TARGET = SECRETS / "baihe-opensandbox.env"
NAME = "BAIHE_SANDBOX_API_KEY"


def make_secrets():
    spec = importlib.util.spec_from_file_location("kr4_make_secrets",
                                                  "/lustre/fsw/portfolios/nemotron/users/hengyuf/swe-task/tools/make_secrets.py")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="verify only (names and OK/MISMATCH)")
    args = parser.parse_args()
    os.umask(0o077)
    ms = make_secrets()
    source = ms.parse_source(ms.SOURCE.read_text())
    if not source.get(NAME):
        print(f"{ms.SOURCE} has no nonempty {NAME}")
        return 2
    if source[NAME] == source.get("CELL3_SANDBOX_API_KEY"):
        print(f"{NAME} equals CELL3_SANDBOX_API_KEY; refusing")
        return 2
    values = {"OPENSANDBOX_DOMAIN": ms.DOMAIN, "OPENSANDBOX_API_KEY": source[NAME], "OPENSANDBOX_TLS_VERIFY": "false",
              "OPENSANDBOX_USE_SERVER_PROXY": "true"}
    text = ms.render(TARGET, values).replace(
        f"# Generated by {ms.S / 'tools/make_secrets.py'} from {ms.SOURCE}; do not edit, rerun the tool.\n",
        f"# Generated by {Path(__file__).resolve()} from {ms.SOURCE} ({NAME}); do not edit, rerun the tool.\n")
    if args.check:
        ok = TARGET.is_file() and TARGET.read_text() == text and stat.S_IMODE(TARGET.stat().st_mode) == 0o600
        print(("OK       " if ok else "MISMATCH ") + f"{TARGET} (mode 600): {', '.join(values)} from {NAME}")
        return 0 if ok else 1
    SECRETS.mkdir(mode=0o700, exist_ok=True)
    os.chmod(SECRETS, 0o700)
    changed = ms.atomic_write(TARGET, text)
    print(f"{'wrote    ' if changed else 'unchanged'} {TARGET} (mode 600): {', '.join(values)}; "
          f"OPENSANDBOX_API_KEY from {NAME}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
