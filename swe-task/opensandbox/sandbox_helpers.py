class HelperError(Exception):
    """A safe-to-display helper error, without upstream response bodies or secrets."""

    def __init__(self, message: str, resource_id: str | None = None):
        super().__init__(message)
        self.resource_id = resource_id


class HelperTimeout(TimeoutError):
    def __init__(self, message: str, resource_id: str | None = None):
        super().__init__(message)
        self.resource_id = resource_id


def _positive(value: float | str) -> float:
    value = float(value)
    if not math.isfinite(value) or value <= 0:
        raise ValueError("duration must be positive and finite")
    return value


def _boolean(value: str, name: str) -> bool:
    if value.lower() in {"1", "true", "yes", "on"}:
        return True
    if value.lower() in {"0", "false", "no", "off"}:
        return False
    raise HelperError(f"{name} must be true or false")


def _literal_env(path: Path) -> dict[str, str]:
    """Read literal assignments only: no shell execution or variable expansion."""
    values = {}
    if not path.exists():
        return values
    for number, line in enumerate(path.read_text().splitlines(), 1):
        match = re.match(r"^\s*(?:export\s+)?(OPENSANDBOX_[A-Z0-9_]+)\s*=\s*(.*?)\s*$", line)
        if not match:
            continue
        key, value = match.groups()
        if value.startswith(("'", '"')):
            quote = value[0]
            end = value.find(quote, 1)
            if end < 0 or (value[end + 1:].strip() and not value[end + 1:].lstrip().startswith("#")):
                raise HelperError(f"Invalid literal env assignment on line {number}")
            value = value[1:end]
        else:
            value = re.split(r"\s+#", value, maxsplit=1)[0].rstrip()
        values[key] = value
    return values


@dataclass(frozen=True)
class Config:
    domain: str
    api_key: str = field(repr=False)
    protocol: str = "https"
    tls_verify: bool = True
    use_server_proxy: bool = True

    @classmethod
    def load(cls, env_file: str | Path = DEFAULT_ENV_FILE) -> "Config":
        values = _literal_env(Path(env_file))
        values.update({key: value for key, value in os.environ.items() if key.startswith("OPENSANDBOX_")})
        domain = values.get("OPENSANDBOX_DOMAIN", "").strip()
        key = values.get("OPENSANDBOX_API_KEY", "")
        if not domain or not key:
            raise HelperError("OPENSANDBOX_DOMAIN and OPENSANDBOX_API_KEY are required")
        protocol = values.get("OPENSANDBOX_PROTOCOL", "https")
        parsed = urlsplit(domain if "://" in domain else f"{protocol}://{domain}")
        if parsed.scheme not in {"http", "https"} or not parsed.netloc or parsed.username or parsed.password or parsed.query or parsed.fragment or parsed.path.rstrip("/"):
            raise HelperError("OPENSANDBOX_DOMAIN must be a host[:port] or HTTP(S) origin")
        return cls(parsed.netloc, key, parsed.scheme,
                   _boolean(values.get("OPENSANDBOX_TLS_VERIFY", "true"), "OPENSANDBOX_TLS_VERIFY"),
                   _boolean(values.get("OPENSANDBOX_USE_SERVER_PROXY", "true"), "OPENSANDBOX_USE_SERVER_PROXY"))


@dataclass
class ExecResult:
    stdout: str = ""
    stderr: str = ""
    exit_code: int = 125
    execution_id: str | None = None
    timed_out: bool = False
    interrupt_attempted: bool = False
    interrupted: bool = False
    remote_running: bool | None = None
    error: str | None = None


def _public(value):
    """Drop credential fields from SDK lifecycle output before serialization."""
    if hasattr(value, "model_dump"):
        value = value.model_dump(mode="json")
    if isinstance(value, dict):
        return {key: _public(item) for key, item in value.items()
                if key.lower() not in {"auth", "api_key", "password", "authorization", "headers"}}
    if isinstance(value, list):
        return [_public(item) for item in value]
    return value


def _safe_error(exc: Exception) -> str:
    if isinstance(exc, HelperError):
        return str(exc)
    status = getattr(exc, "status_code", None)
    return type(exc).__name__ + (f" (HTTP {status})" if isinstance(status, int) else "")


def _output_path(path: str | Path) -> Path:
    path = Path(path).expanduser().resolve()
    roots = (ARTIFACT_ROOT.resolve(), Path("/tmp"), Path("/raid/scratch"))
    if not any(path.is_relative_to(root) for root in roots):
        raise HelperError("Local output must be under this helper directory, /tmp, or /raid/scratch")
    return path


class Client:
    """Use one async context in one event loop; IDs survive client disconnection."""

    def __init__(self, config: Config, timeout: float = DEFAULT_TIMEOUT):
        self.config = config
        self.timeout = _positive(timeout)
        self.connection = None
        self.manager = None
        self._http = None
        self._transport = None

    async def __aenter__(self):
        if self._transport is not None:
            raise HelperError("Client context is already open")
        self._transport = httpx.AsyncHTTPTransport(verify=self.config.tls_verify, retries=0)
        headers = {"OPEN-SANDBOX-API-KEY": self.config.api_key} if self.config.use_server_proxy else {}
        self.connection = ConnectionConfig(
            domain=self.config.domain, protocol=self.config.protocol, api_key=self.config.api_key,
            headers=headers, use_server_proxy=self.config.use_server_proxy,
            request_timeout=timedelta(seconds=self.timeout),
            transport=self._transport, disable_metrics=True,
        )
        # This HTTP client and all SDK adapters share our explicitly owned transport.
        self._http = httpx.AsyncClient(transport=self._transport, timeout=self.timeout)
        try:
            self.manager = await SandboxManager.create(connection_config=self.connection)
        except BaseException:
            await self.__aexit__(None, None, None)
            raise
        return self

    async def __aexit__(self, *_):
        try:
            if self._http is not None:
                async with asyncio.timeout(CLEANUP_TIMEOUT):
                    await self._http.aclose()
        finally:
            self._http = self._transport = self.manager = self.connection = None

    def _seconds(self, timeout):
        if self.connection is None:
            raise HelperError("Use Client inside 'async with'")
        return self.timeout if timeout is None else _positive(timeout)

    async def _connect(self, sandbox_id: str):
        if not sandbox_id:
            raise HelperError("Sandbox ID is required")
        return await Sandbox.connect(sandbox_id, connection_config=self.connection, skip_health_check=True)

    async def create(self, image=None, *, snapshot_id=None, ttl=600, timeout=None,
                     env=None, resource=None, metadata=None, network="deny",
                     registry_username_env=None, registry_password_env=None) -> dict:
        seconds = self._seconds(timeout)
        if bool(image) == bool(snapshot_id):
            raise HelperError("Specify exactly one of image or snapshot_id")
        if network not in {"allow", "deny"}:
            raise HelperError("network must be allow or deny")
        if bool(registry_username_env) != bool(registry_password_env):
            raise HelperError("Both registry credential environment names are required")
        if registry_username_env:
            if not image:
                raise HelperError("Registry credentials require an image")
            username = os.environ.get(registry_username_env, "")
            password = os.environ.get(registry_password_env, "")
            if not username or not password:
                raise HelperError("Registry credential environment variable is unset or empty")
            image = SandboxImageSpec(image, auth=SandboxImageAuth(username=username, password=password))
        # Cold image pulls/restores may hold the create POST open for the full deadline.
        connection = self.connection.model_copy(update={"request_timeout": timedelta(seconds=seconds)})
        task = asyncio.create_task(Sandbox.create(
            image=image, snapshot_id=snapshot_id, timeout=timedelta(seconds=_positive(ttl)),
            ready_timeout=timedelta(seconds=seconds), env=env, resource=resource,
            metadata=metadata, network_policy=NetworkPolicy(default_action=network),
            connection_config=connection,
        ))
        # Never retry create: a lost HTTP response can leave an unknown remote ID.
        try:
            async with asyncio.timeout(seconds):
                sandbox = await asyncio.shield(task)
        except (TimeoutError, asyncio.CancelledError) as exc:
            # SDK 0.1.15 catches cancellation and tries to kill its new sandbox. Give
            # that cleanup five seconds, then cancel its kill request as well.
            known_id = None
            task.cancel()
            try:
                completed = await asyncio.wait_for(task, CLEANUP_TIMEOUT)
                known_id = completed.id
            except (Exception, asyncio.CancelledError):
                pass
            if isinstance(exc, TimeoutError):
                raise HelperTimeout("Create deadline exceeded; inspect metadata before retrying", known_id) from exc
            if known_id is not None:
                exc.resource_id = known_id
            raise
        return {"id": sandbox.id, "ttl_seconds": ttl, "network": network}

    async def exec(self, sandbox_id: str, command: str, *, cwd=None, timeout=None) -> ExecResult:
        seconds = self._seconds(timeout)
        if not command.strip():
            raise HelperError("Command cannot be empty")
        result, stdout, stderr = ExecResult(), [], []
        sandbox = None

        async def on_init(event):
            result.execution_id = event.id

        async def on_stdout(event):
            stdout.append(event.text)

        async def on_stderr(event):
            stderr.append(event.text)

        async def interrupt_owned_command():
            if sandbox is None or not result.execution_id:
                return
            result.interrupt_attempted = True
            try:
                async with asyncio.timeout(CLEANUP_TIMEOUT):
                    try:
                        await sandbox.commands.interrupt(result.execution_id)
                        result.interrupted = True  # Request accepted, not a process-tree guarantee.
                    except Exception:
                        # The server-side timeout may have stopped this command first.
                        result.error = "Command interrupt could not be confirmed"
                        status = await sandbox.commands.get_command_status(result.execution_id)
                        result.remote_running = status.running
                        if status.running is False:
                            result.error = None
            except Exception:
                result.error = "Command interrupt could not be confirmed"

        try:
            async with asyncio.timeout(seconds) as deadline:
                sandbox = await self._connect(sandbox_id)
                remaining = max(0.001, deadline.when() - asyncio.get_running_loop().time())
                execution = await sandbox.commands.run(
                    command, opts=RunCommandOpts(working_directory=cwd, timeout=timedelta(seconds=remaining)),
                    handlers=ExecutionHandlers(on_init=on_init, on_stdout=on_stdout,
                                               on_stderr=on_stderr, skip_accumulation=True),
                )
                result.execution_id = execution.id or result.execution_id
                result.exit_code = execution.exit_code if execution.exit_code is not None else 125
                if execution.exit_code is not None:
                    result.remote_running = False
                if execution.exit_code is None:
                    result.error = "Remote command ended without a known exit code"
        except TimeoutError:
            result.exit_code, result.timed_out = 124, True
            await interrupt_owned_command()
        except asyncio.CancelledError:
            await interrupt_owned_command()
            raise
        finally:
            # Output events are line chunks without their newline; rejoin them as the SDK's Execution.text does.
            result.stdout = "\n".join(chunk.rstrip("\n") for chunk in stdout)
            result.stderr = "\n".join(chunk.rstrip("\n") for chunk in stderr)
        return result

    async def info(self, sandbox_id, *, timeout=None):
        async with asyncio.timeout(self._seconds(timeout)):
            return _public(await self.manager.get_sandbox_info(sandbox_id))

    async def find(self, metadata, *, page=1, page_size=100, timeout=None):
        """Read one explicit page of exact metadata matches; never delete results."""
        if not metadata:
            raise HelperError("At least one metadata filter is required")
        async with asyncio.timeout(self._seconds(timeout)):
            result = await self.manager.list_sandbox_infos(SandboxFilter(
                metadata=metadata, page=page, page_size=page_size))
        return {"sandbox_infos": [_public(item) for item in result.sandbox_infos
                    if all((item.metadata or {}).get(key) == value for key, value in metadata.items())],
                "pagination": _public(result.pagination)}

    async def renew(self, sandbox_id, ttl, *, timeout=None):
        async with asyncio.timeout(self._seconds(timeout)):
            result = await self.manager.renew_sandbox(sandbox_id, timedelta(seconds=_positive(ttl)))
            return {"id": sandbox_id, **_public(result)}

    async def delete(self, sandbox_id, *, timeout=None):
        async with asyncio.timeout(self._seconds(timeout)):
            await self.manager.kill_sandbox(sandbox_id)
        return {"id": sandbox_id, "deleted": True}

    async def snapshot(self, sandbox_id, *, name=None, wait=False, timeout=None):
        snapshot_id = None
        try:
            async with asyncio.timeout(self._seconds(timeout)):
                info = await self.manager.create_snapshot(sandbox_id, name=name)
                snapshot_id = info.id
                while wait and info.status.state.lower() != "ready":
                    if info.status.state.lower() in {"failed", "error", "deleted"}:
                        raise HelperError(f"Snapshot {snapshot_id} failed; inspect snapshot-info", snapshot_id)
                    await asyncio.sleep(1)
                    info = await self.manager.get_snapshot(snapshot_id)
                return _public(info)
        except TimeoutError as exc:
            raise HelperTimeout("Snapshot deadline exceeded; do not repeat creation blindly", snapshot_id) from exc
        except Exception as exc:
            # Preserve native status_code while retaining the checkpoint ID on polling failures.
            if snapshot_id is not None:
                exc.resource_id = snapshot_id
            raise

    async def snapshot_info(self, snapshot_id, *, timeout=None):
        async with asyncio.timeout(self._seconds(timeout)):
            return _public(await self.manager.get_snapshot(snapshot_id))

    async def delete_snapshot(self, snapshot_id, *, timeout=None):
        async with asyncio.timeout(self._seconds(timeout)):
            await self.manager.delete_snapshot(snapshot_id)
        return {"id": snapshot_id, "deleted": True}

    async def restore_snapshot(self, snapshot_id, **kwargs):
        return await self.create(snapshot_id=snapshot_id, **kwargs)

    async def upload(self, sandbox_id, local, remote, *, timeout=None):
        local = Path(local).expanduser()
        async with asyncio.timeout(self._seconds(timeout)):
            sandbox = await self._connect(sandbox_id)
            with local.open("rb") as source:
                await sandbox.files.write_file(remote, source, mode=0o644)
        return {"id": sandbox_id, "path": remote, "bytes": local.stat().st_size}

    async def download(self, sandbox_id, remote, local, *, timeout=None):
        destination = _output_path(local)
        destination.parent.mkdir(parents=True, exist_ok=True)
        temporary = None
        count = 0
        try:
            async with asyncio.timeout(self._seconds(timeout)):
                sandbox = await self._connect(sandbox_id)
                endpoint = await sandbox.get_endpoint(DEFAULT_EXECD_PORT)
                headers = {**self.connection.headers, **endpoint.headers}
                url = f"{self.config.protocol}://{endpoint.endpoint}/files/download"
                # Explicit response ownership closes a cancelled stream immediately.
                async with self._http.stream("GET", url, headers=headers, params={"path": remote}) as response:
                    response.raise_for_status()
                    with tempfile.NamedTemporaryFile(dir=destination.parent, prefix=".download-", delete=False) as output:
                        temporary = Path(output.name)
                        async for chunk in response.aiter_bytes(64 * 1024):
                            output.write(chunk)
                            count += len(chunk)
                    temporary.replace(destination)
                    temporary = None
        finally:
            if temporary is not None:
                temporary.unlink(missing_ok=True)
        return {"id": sandbox_id, "path": str(destination), "bytes": count}


def _pairs(values):
    result = {}
    for value in values or []:
        key, separator, item = value.partition("=")
        if not separator or not key:
            raise HelperError("Expected KEY=VALUE")
        result[key] = item
    return result or None


def _assignment(value):
    if "=" not in value or not value.partition("=")[0]:
        raise argparse.ArgumentTypeError("expected KEY=VALUE")
    return value


def _parser():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--env-file", default=str(DEFAULT_ENV_FILE))
    commands = parser.add_subparsers(dest="action", required=True)

    def command(name, id_name=None):
        sub = commands.add_parser(name)
        if id_name:
            sub.add_argument(id_name)
        sub.add_argument("--timeout", type=_positive, default=DEFAULT_TIMEOUT,
                         help="operation deadline in seconds (plus bounded cleanup)")
        return sub

    def creation(sub):
        sub.add_argument("--ttl", type=_positive, default=600)
        sub.add_argument("--env", action="append", type=_assignment)
        sub.add_argument("--resource", action="append", type=_assignment)
        sub.add_argument("--metadata", action="append", type=_assignment)
        sub.add_argument("--network", choices=("allow", "deny"), default="deny")

    sub = command("create")
    source = sub.add_mutually_exclusive_group(required=True)
    source.add_argument("--image")
    source.add_argument("--snapshot-id")
    creation(sub)
    sub.add_argument("--registry-username-env")
    sub.add_argument("--registry-password-env")
    sub = command("exec", "sandbox_id")
    sub.add_argument("command", help="one shell command string")
    sub.add_argument("--workdir")
    sub.add_argument("--json", action="store_true")
    sub = command("upload", "sandbox_id")
    sub.add_argument("local")
    sub.add_argument("remote")
    sub = command("download", "sandbox_id")
    sub.add_argument("remote")
    sub.add_argument("local")
    command("info", "sandbox_id")
    sub = command("find")
    sub.add_argument("--metadata", action="append", type=_assignment, required=True)
    sub.add_argument("--page", type=int, default=1)
    sub.add_argument("--page-size", type=int, default=100)
    sub = command("renew", "sandbox_id")
    sub.add_argument("--ttl", type=_positive, required=True)
    command("delete", "sandbox_id")
    sub = command("snapshot", "sandbox_id")
    sub.add_argument("--name")
    command("snapshot-info", "snapshot_id")
    command("delete-snapshot", "snapshot_id")
    creation(command("restore-snapshot", "snapshot_id"))
    for name in ("backup", "export-build-context"):
        sub = command(name, "sandbox_id")
        sub.add_argument("--workdir", required=True)
        sub.add_argument("--output-dir", required=True)
        if name == "export-build-context":
            sub.add_argument("--base-image", required=True)
            sub.add_argument("--setup-script")
    sub = command("restore", "sandbox_id")
    sub.add_argument("--backup-dir", required=True)
    sub.add_argument("--destination", required=True)
    sub.add_argument("--replace", action="store_true")
    return parser


async def _run(args):
    async with Client(Config.load(args.env_file), timeout=args.timeout) as client:
        action = args.action
        if action in {"create", "restore-snapshot"}:
            kwargs = dict(ttl=args.ttl, env=_pairs(args.env), resource=_pairs(args.resource),
                          metadata=_pairs(args.metadata), network=args.network)
            if action == "create":
                return await client.create(image=args.image, snapshot_id=args.snapshot_id,
                    registry_username_env=args.registry_username_env,
                    registry_password_env=args.registry_password_env, **kwargs)
            return await client.restore_snapshot(args.snapshot_id, **kwargs)
        if action == "exec":
            return await client.exec(args.sandbox_id, args.command, cwd=args.workdir)
        if action == "upload":
            return await client.upload(args.sandbox_id, args.local, args.remote)
        if action == "download":
            return await client.download(args.sandbox_id, args.remote, args.local)
        if action == "info":
            return await client.info(args.sandbox_id)
        if action == "find":
            return await client.find(_pairs(args.metadata), page=args.page, page_size=args.page_size)
        if action == "renew":
            return await client.renew(args.sandbox_id, args.ttl)
        if action == "delete":
            return await client.delete(args.sandbox_id)
        if action == "snapshot":
            return await client.snapshot(args.sandbox_id, name=args.name, wait=True)
        if action == "snapshot-info":
            return await client.snapshot_info(args.snapshot_id)
        if action == "delete-snapshot":
            return await client.delete_snapshot(args.snapshot_id)
        import workspace_ops
        # Composite operations have one deadline, rather than one per subcommand.
        async with asyncio.timeout(args.timeout):
            if action == "backup":
                return await workspace_ops.backup(client, args.sandbox_id, args.workdir, args.output_dir)
            if action == "restore":
                return await workspace_ops.restore(client, args.sandbox_id, args.backup_dir, args.destination, replace=args.replace)
            return await workspace_ops.export_build_context(client, args.sandbox_id, args.workdir,
                args.output_dir, args.base_image, setup_script=args.setup_script)


def main(argv=None):
    parser = _parser()
    args = parser.parse_args(argv)
    if args.action == "create":
        if bool(args.registry_username_env) != bool(args.registry_password_env):
            parser.error("both registry credential environment names are required")
        if args.registry_username_env and not args.image:
            parser.error("registry credentials require --image")
    if args.action == "find" and (args.page < 1 or args.page_size < 1):
        parser.error("--page and --page-size must be positive")
    # SDK exception logging includes upstream bodies; expose only safe CLI errors.
    logging.getLogger("opensandbox").setLevel(logging.CRITICAL)
    try:
        result = asyncio.run(_run(args))
        if isinstance(result, ExecResult):
            if args.json:
                print(json.dumps(asdict(result)))
            else:
                sys.stdout.write(result.stdout)
                sys.stderr.write(result.stderr)
                if result.timed_out or result.error:
                    print(json.dumps({"exit_code": result.exit_code, "execution_id": result.execution_id,
                        "timed_out": result.timed_out, "interrupt_attempted": result.interrupt_attempted,
                        "interrupted": result.interrupted, "remote_running": result.remote_running,
                        "error": result.error}), file=sys.stderr)
            return _cli_exit_code(result.exit_code)
        print(json.dumps(result))
        return 0
    except KeyboardInterrupt:
        print(json.dumps({"error": "Interrupted"}), file=sys.stderr)
        return 130
    except TimeoutError as exc:
        print(json.dumps({"error": "Operation deadline exceeded; remote state may require inspection",
                          "resource_id": getattr(exc, "resource_id", None)}), file=sys.stderr)
        return 124
    except Exception as exc:
        print(json.dumps({"error": _safe_error(exc),
                          "resource_id": getattr(exc, "resource_id", None)}), file=sys.stderr)
        return 125


def _cli_exit_code(code: int) -> int:
    """POSIX exit statuses are 0..255; negative signal codes remain in JSON only."""
    return code if 0 <= code <= 255 else 125


if __name__ == "__main__":
    raise SystemExit(main())
