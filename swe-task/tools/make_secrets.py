#!/usr/bin/env python3
"""Generate the swe-task credential files from hengyuf's credentials file. Never prints secret values.

    python3 -I -B tools/make_secrets.py           # write atp/.env and secrets/opensandbox.env (mode 600)
    python3 -I -B tools/make_secrets.py --check   # verify modes, exact key sets and values (sha256), print OK/MISMATCH

The source is read literally (no shell evaluation): optional `export `, single/double-quoted or bare values,
full-line and ` #` trailing comments. Values with shell-sensitive characters must be single-quoted there.
Outputs use single-quoted values, which ATP's deepswe_stage.read_dotenv (shlex) and the opensandbox
helper's literal parser both read back verbatim. Stdlib only; works under `python3 -I`.
"""
import sys

sys.dont_write_bytecode = True

import argparse
import hashlib
import importlib.util
import os
from pathlib import Path
import re
import stat
import tempfile

SOURCE = Path("/lustre/fsw/portfolios/nemotron/users/hengyuf/.env")
HUB_KEYS = ("NVAPI_KEY_NEW", "NVAPI_KEY_OFFICIAL", "NVAPI_KEY_OFFICIAL_1", "NVAPI_KEY_OFFICIAL_2", "NVAPI_KEY_NEW_3",
            "NVAPI_KEY_NEW_2")  # = synth/common.HUB_KEYS (NVAPI_KEY ran out 2026-10-17; NEW_2 added 2026-11-02)
HUB_KEY_ACTIVE = Path("/lustre/fsw/portfolios/nemotron/users/hengyuf/swe-task/synth/hub_key_active.txt")


def hub_key_name() -> str:
    """= synth/common.hub_key_name(): the active hub key's NAME (this tool stays stdlib-only and import-free)."""
    try:
        name = HUB_KEY_ACTIVE.read_text().strip()
    except OSError:
        name = ""
    return name if name in HUB_KEYS else HUB_KEYS[0]
S = Path("/lustre/fsw/portfolios/nemotron/users/hengyuf/swe-task")
APP = S / "atp"
APP_ENV = APP / ".env"
SECRETS = S / "secrets"
OPENSANDBOX_ENV = SECRETS / "opensandbox.env"
DOMAIN = "k8s-opensand-opensand-6b4cff3a21-1bdfa951f626dc97.elb.us-east-2.amazonaws.com"  # https (default)
KEY = re.compile(r"[A-Za-z_][A-Za-z0-9_]*")
SHELL_SPECIAL = set("$`\\\"'!;&|<>(){}*?[]~")


def parse_source(text: str) -> dict:
    """KEY=value assignments read literally; errors name line numbers only, never values."""
    values = {}
    for number, raw in enumerate(text.splitlines(), 1):
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        if line.startswith(("export ", "export\t")):
            line = line[7:].lstrip()
        key, separator, value = line.partition("=")
        key, value = key.strip(), value.strip()
        if not separator or not KEY.fullmatch(key):
            raise ValueError(f"{SOURCE}: line {number} is not a KEY=value assignment")
        if value[:1] in ("'", '"'):
            end = value.find(value[0], 1)
            rest = value[end + 1:].strip() if end > 0 else ""
            if end < 0 or (rest and not rest.startswith("#")):
                raise ValueError(f"{SOURCE}: line {number} has an unterminated or trailing-text quoted value")
            if value[0] == '"' and set(value[1:end]) & set("$`\\"):
                raise ValueError(f"{SOURCE}: line {number} needs shell expansion; single-quote it instead")
            value = value[1:end]
        else:
            value = re.split(r"\s+#", value, maxsplit=1)[0].strip()
            if any(char.isspace() or char in SHELL_SPECIAL for char in value):
                raise ValueError(f"{SOURCE}: line {number} has shell-sensitive characters; single-quote it")
        values[key] = value
    return values


def targets(source: dict) -> dict:
    """The exact contents of both generated files (contract: docs/port-contract.md, SECRETS)."""
    missing = [name for name in (hub_key_name(), "CELL3_SANDBOX_API_KEY", "HF_TOKEN") if not source.get(name)]
    if missing:
        raise ValueError(f"{SOURCE} lacks nonempty {', '.join(missing)}")
    sandbox_key = source["CELL3_SANDBOX_API_KEY"]
    return {
        APP_ENV: {"NVIDIA_API_KEY": source[hub_key_name()], "OPENSANDBOX_DOMAIN": DOMAIN,
                  "OPENSANDBOX_API_KEY": sandbox_key, "OPENSANDBOX_TLS_VERIFY": "false", "HF_TOKEN": source["HF_TOKEN"]},
        OPENSANDBOX_ENV: {"OPENSANDBOX_DOMAIN": DOMAIN, "OPENSANDBOX_API_KEY": sandbox_key,
                          "OPENSANDBOX_TLS_VERIFY": "false", "OPENSANDBOX_USE_SERVER_PROXY": "true"},
    }


def render(path: Path, values: dict) -> str:
    for key, value in values.items():
        if not value or any(char in value for char in "'\n\r\0"):
            raise ValueError(f"{key} is empty or cannot be single-quoted safely")
    header = (f"# Generated by {S / 'tools/make_secrets.py'} from {SOURCE}; do not edit, rerun the tool.\n"
              f"# Mode 600. Keys: {', '.join(values)}\n")
    return header + "".join(f"{key}='{value}'\n" for key, value in values.items())


def atomic_write(path: Path, text: str) -> bool:
    """Write via a 0600 temporary file in the same directory; False if already identical."""
    if path.is_file() and not path.is_symlink() and path.read_text() == text:
        os.chmod(path, 0o600)
        return False
    descriptor, temporary = tempfile.mkstemp(prefix=f".{path.name}.", suffix=".tmp", dir=path.parent)
    try:
        with os.fdopen(descriptor, "w") as stream:
            stream.write(text)
            stream.flush()
            os.fsync(stream.fileno())
        os.chmod(temporary, 0o600)
        os.replace(temporary, path)
    except BaseException:
        Path(temporary).unlink(missing_ok=True)
        raise
    directory = os.open(path.parent, os.O_RDONLY | os.O_DIRECTORY)
    try:
        os.fsync(directory)
    finally:
        os.close(directory)
    return True


def atp_parser():
    """ATP's own reader of the app .env (deepswe_stage.read_dotenv), loaded from this app's scripts."""
    spec = importlib.util.spec_from_file_location("atp_deepswe_stage", APP / "scripts/deepswe_stage.py")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module.read_dotenv


def helper_parse(path: Path) -> dict:
    """The opensandbox helper's literal OPENSANDBOX_* reader (sandbox_helpers._literal_env semantics)."""
    values = {}
    for line in path.read_text().splitlines():
        match = re.match(r"^\s*(?:export\s+)?(OPENSANDBOX_[A-Z0-9_]+)\s*=\s*(.*?)\s*$", line)
        if not match:
            continue
        key, value = match.groups()
        if value.startswith(("'", '"')):
            end = value.find(value[0], 1)
            if end < 0 or (value[end + 1:].strip() and not value[end + 1:].lstrip().startswith("#")):
                raise ValueError(f"{path}: invalid literal assignment for {key}")
            value = value[1:end]
        else:
            value = re.split(r"\s+#", value, maxsplit=1)[0].rstrip()
        values[key] = value
    return values


def digest(value) -> str:
    return hashlib.sha256(str(value).encode()).hexdigest()


def check(expected: dict) -> bool:
    ok = True

    def report(good, message):
        nonlocal ok
        ok &= bool(good)
        print(("OK       " if good else "MISMATCH ") + message, flush=True)

    mode = stat.S_IMODE(SECRETS.stat().st_mode) if SECRETS.is_dir() else None
    report(mode == 0o700 and not SECRETS.is_symlink(), f"{SECRETS} is a directory with mode 700")
    report(not (APP / ".api").exists(), f"{APP / '.api'} is absent (single NVIDIA credential)")
    read_dotenv = atp_parser()
    for path, values in expected.items():
        if not path.is_file() or path.is_symlink():
            report(False, f"{path} exists as a regular file")
            continue
        info = path.stat()
        report(stat.S_IMODE(info.st_mode) == 0o600 and info.st_uid == os.getuid(), f"{path} mode 600, owned by you")
        readers = {"literal": parse_source(path.read_text())}
        if path == APP_ENV:
            readers["ATP read_dotenv"] = read_dotenv(path)
        else:
            readers["opensandbox helper"] = helper_parse(path)
        for reader, parsed in readers.items():
            report(list(parsed) == list(values), f"{path} [{reader}] has exactly keys {', '.join(values)}")
            for key, value in values.items():
                report(digest(parsed.get(key)) == digest(value), f"{path} [{reader}] {key} matches the source")
    return ok


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="verify only; print OK/MISMATCH lines")
    args = parser.parse_args()
    os.umask(0o077)
    source_mode = stat.S_IMODE(SOURCE.stat().st_mode)
    if source_mode & 0o077:
        print(f"WARNING: {SOURCE} has mode {source_mode:03o} (readable by others); consider chmod 600", flush=True)
    expected = targets(parse_source(SOURCE.read_text()))
    if args.check:
        return 0 if check(expected) else 1
    SECRETS.mkdir(mode=0o700, exist_ok=True)
    os.chmod(SECRETS, 0o700)
    for path, values in expected.items():
        changed = atomic_write(path, render(path, values))
        print(f"{'wrote    ' if changed else 'unchanged'} {path} (mode 600): {', '.join(values)}", flush=True)
    return 0 if check(expected) else 1


if __name__ == "__main__":
    raise SystemExit(main())
